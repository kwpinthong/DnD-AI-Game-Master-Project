import { ROOM_PATH } from '../room.ts';
import { CONTRACT, CONTRACT_SCREENS, PENDING_FIELDS, type ContractItem } from './registry.ts';

export const CONTRACT_DOC_BEGIN = '<!-- contract:begin (generated by `pnpm --filter @isekai/protocol contract:docs`, do not edit) -->';
export const CONTRACT_DOC_END = '<!-- contract:end -->';

const AUDIENCE: Record<ContractItem['audience'], string> = { player: 'ผู้เล่น', gm: 'GM คน', admin: 'ผู้ดูแล', any: 'ทุกคน' };
const STATUS = { ready: 'ready', pending: '**pending**' } as const;

const cell = (text: string) => text.replace(/\|/g, '\\|');

function channel(item: ContractItem): string {
  if (item.kind === 'http') return `\`${item.method} ${item.path}\``;
  return item.direction === 'client' ? `socket → \`${item.type}\`` : `socket ← \`${item.type}\``;
}

function payload(item: ContractItem): string {
  if (item.kind === 'socket') return `\`${item.schema}\``;
  const req = item.request ? `\`${item.request}\`` : '-';
  const res = item.response ? `\`${item.response}\`` : '204';
  return `${req} → ${res}`;
}

/** The generated part of docs/contract.md: page → endpoint / event → schema → ready / pending + owner. */
export function renderContractDocs(): string {
  const lines: string[] = [CONTRACT_DOC_BEGIN, ''];
  const items = CONTRACT.length;
  const readyCount = CONTRACT.filter((i) => i.status === 'ready').length;
  lines.push(
    `endpoint / socket event ${items} รายการ: ready ${readyCount}, pending ${items - readyCount} · field ที่ยัง pending ใน schema ที่ส่งอยู่แล้ว ${PENDING_FIELDS.length} รายการ · socket = \`${ROOM_PATH}\` · ทุกคำตอบที่ไม่ใช่ 2xx เป็น \`ApiError\``,
    '',
    '### หน้า → endpoint / event → schema',
    '',
    '| หน้า | endpoint / event | schema (request → response) | ผู้รับ | สถานะ | task เจ้าของ | หมายเหตุ |',
    '|---|---|---|---|---|---|---|',
  );
  for (const screen of CONTRACT_SCREENS) {
    for (const item of CONTRACT.filter((i) => (i.screens as readonly string[]).includes(screen.id))) {
      lines.push(
        `| ${cell(screen.title)} | ${channel(item)} | ${payload(item)} | ${AUDIENCE[item.audience]} | ${STATUS[item.status]} | ${item.owner} | ${cell(item.note ?? '')} |`,
      );
    }
  }
  lines.push('', '### field ที่ยัง pending (schema มีแล้ว server ยังไม่ส่ง / ยังไม่รับ)', '', '| schema.field | หน้า | task เจ้าของ | หมายเหตุ |', '|---|---|---|---|');
  for (const f of PENDING_FIELDS) {
    const titles = f.screens.map((id) => CONTRACT_SCREENS.find((s) => s.id === id)!.title).join(', ');
    lines.push(`| \`${f.schema}.${f.path}${f.value ? ` = '${f.value}'` : ''}\` | ${cell(titles)} | ${f.owner} | ${cell(f.note)} |`);
  }
  lines.push('', CONTRACT_DOC_END);
  return lines.join('\n');
}
